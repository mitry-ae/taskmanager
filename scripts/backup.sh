#!/bin/bash

# -e: остановить скрипт, если любая команда завершилась с ошибкой
# -u: остановить скрипт, если используется переменная, которая не задана (опечатка в имени и т.п.)
# -o pipefail: если в цепочке "команда1 | команда2" упадёт команда1, весь pipe тоже
#              считается упавшим (без этого bash смотрит только на код возврата последней команды)
set -euo pipefail

# Узнаём, где физически лежит сам этот файл, и берём от этого абсолютные пути.
# Так скрипт работает одинаково независимо от того, откуда его запустили
# (deploy может вызвать его из любой текущей директории).
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"

# .env читает сам docker compose, но этот bash-процесс — не docker compose,
# поэтому переменные вроде POSTGRES_USER нужно явно загрузить в его окружение.
# set -a  -> все переменные, объявленные после этой строки, автоматически экспортируются
# source  -> построчно выполняет .env как обычные присваивания (VAR=value)
# set +a  -> выключаем автоэкспорт обратно, чтобы не тащить его дальше по скрипту
set -a
source "$PROJECT_DIR/.env"
set +a

BACKUP_DIR="$PROJECT_DIR/backups"
RETENTION_COUNT=3
TIMESTAMP="$(date +%Y%m%d_%H%M%S)"
BACKUP_FILE="$BACKUP_DIR/backup_${TIMESTAMP}.dump"

# -p: создать директорию, если её ещё нет, и не ругаться, если она уже есть
mkdir -p "$BACKUP_DIR"

# docker compose ищет docker-compose.yml в текущей директории, поэтому
# явно переходим в корень проекта перед вызовом exec
cd "$PROJECT_DIR"

echo "Делаю бэкап базы ${POSTGRES_DB}..."

# exec -T   — запустить команду в уже работающем контейнере postgres без TTY
#             (TTY добавляет служебные символы в вывод и портит файл дампа)
# pg_dump -Fc — дамп в "custom format": компактнее обычного SQL и поддерживает
#             частичный/параллельный restore
# > "$BACKUP_FILE" — перенаправляем вывод команды в файл на хосте
docker compose exec -T postgres pg_dump -U "$POSTGRES_USER" -Fc "$POSTGRES_DB" > "$BACKUP_FILE"

# ВАЖНО: bash создаёт файл из "> $BACKUP_FILE" ещё до того, как pg_dump начал
# писать в него данные. Если pg_dump упал (например, неверный пароль),
# set -e остановит скрипт на строке выше — но на всякий случай ещё раз
# проверяем явно: -s означает "файл существует и его размер больше 0 байт".
if [ ! -s "$BACKUP_FILE" ]; then
  echo "Бэкап пустой, что-то пошло не так" >&2
  rm -f "$BACKUP_FILE"
  exit 1
fi

# 600 = читать/писать может только владелец файла. Дамп содержит хэши
# паролей пользователей приложения, ему не место с правами "на чтение всем".
chmod 600 "$BACKUP_FILE"

echo "Бэкап готов: $BACKUP_FILE ($(du -h "$BACKUP_FILE" | cut -f1))"

# Ротация: оставляем только последние RETENTION_COUNT файлов.
# ls -t          — список файлов, сначала самые новые
# tail -n +N+1   — пропустить первые N строк (свежие бэкапы) и вывести всё, что после
# xargs rm -f    — удалить то, что осталось (старые бэкапы)
# Если файлов меньше или равно RETENTION_COUNT, tail ничего не выведет — и rm не вызовется.
ls -t "$BACKUP_DIR"/backup_*.dump | tail -n +$((RETENTION_COUNT + 1)) | xargs -r rm -f

echo "Готово"
